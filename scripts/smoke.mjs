import assert from 'node:assert/strict';
const base=process.env.TEST_BASE_URL||'http://127.0.0.1:3000';
const health=await fetch(base+'/api/health').then(r=>r.json());assert.equal(health.demo,true);
let r=await fetch(base+'/api/admin');assert.equal(r.status,401);
const session=await fetch(base+'/api/session',{method:'POST',body:'{}'}).then(r=>r.json());assert.equal(session.owner,false);
assert.equal(session.liveMusic,false,'Run this sample test with MUSIC_MODE=sample; use scripts/live-smoke.mjs for live music.');
const api=async(path,body)=>{const r=await fetch(base+'/api'+path,{method:body?'POST':'GET',headers:{Authorization:`Bearer ${session.token}`,'Content-Type':'application/json'},body:body?JSON.stringify(body):undefined});return {status:r.status,data:await r.json()};};
assert.equal((await api('/admin')).status,403);
assert.equal((await api('/admin/ban',{id:123,type:'user',banned:true})).status,403);
assert.equal((await api('/search?q=orbit')).data.tracks[0].id,'demo-orbit');
assert.equal((await api('/play',{id:'demo-orbit'})).data.demo,true);
assert.equal((await api('/play',{id:'../../secret'})).status,404);
let u=(await api('/profile',{playlist:'Test collection'})).data;
u=(await api('/playlist/track',{playlistId:u.playlists.at(-1).id,trackId:'demo-orbit'})).data;
assert.ok(u.playlists.at(-1).tracks.includes('demo-orbit'));
assert.equal((await api('/rooms',{name:'Not a group'})).status,403);
assert.deepEqual((await api('/rooms')).data.rooms,[]);
assert.equal((await fetch(base+'/')).status,200);
assert.equal((await fetch(base+'/style.css')).status,200);
console.log('Passed: health, auth gates, owner denial, search, playback, invalid ID, playlist persistence, group-only room creation gate, no public room directory, static routes.');
